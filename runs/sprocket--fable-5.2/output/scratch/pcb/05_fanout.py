"""Hand-drawn fan-out of U1: header GPIOs, QSPI to flash and PSRAM, crystal, decoupling, and via stubs for
the nets the autorouter finishes. Runs 04_handroute.py first (which clears all copper) and saves both.
Coordinates are mm relative to the board corner."""
import importlib

h = importlib.import_module('04_handroute')
pad, T, V, pin, bt = h.pad, h.T, h.V, h.pin, h.bt
B = bt.BL_B_Cu
S, P = 0.15, 0.2                       # signal and power stub widths


def gnd(p, x, y, *mid):
    T('GND', P, p, *mid, (x, y))
    V('GND', x, y)


# ================= top row (pins 31..45, y 9.25) =================
j6 = lambda n: pad('J6', str(n))
# GP19..GP22 and the two ADC pins run north-west to the header in parallel lanes
T('/GP19', S, pin(31), (35.8, 4.15), j6(9))
T('/GP20', S, pin(32), (35.4, 6.0), (30.67, 1.27), j6(8))
T('/GP21', S, pin(33), (35.0, 6.05), (33.5, 4.55), (31.12, 4.55), j6(7))
T('/GP22', S, pin(34), (34.6, 6.1), (33.35, 4.85), (28.88, 4.85), j6(6))
T('/GP26_A0', S, pin(40), (32.2, 6.0), (31.35, 5.15), (26.64, 5.15), j6(5))
T('/GP27_A1', S, pin(41), (31.8, 6.025), (31.225, 5.45), (24.4, 5.45), j6(4))
T('/VBAT_SENSE', S, pin(42), (31.4, 6.05), (31.1, 5.75), (22.4, 5.75))
V('/VBAT_SENSE', 22.4, 5.75)
# vias inside the pad ring
YT = 10.325
for net, n, x in (('/WL_CLK', 43, 31.2), ('/WL_CS', 37, 33.1), ('/WL_D', 36, 33.85), ('/WL_ON', 35, 34.6)):
    T(net, S, pin(n), (pin(n)[0], 9.9), (x, YT))
    V(net, x, YT)
T('+1V1', S, pin(39), (32.6, 9.9), (32.3, YT))
V('+1V1', 32.3, YT)
V('+3V3', 30.45, YT)
T('+3V3', S, pin(45), (30.2, 9.9), (30.45, YT), (30.6, 9.9), pin(44))
T('+3V3', S, pin(49), (30.1, 11.1), (30.45, 10.75), (30.45, YT))
# decoupling north of the package
c13, c19, c17, c12 = pad('C13', '1'), pad('C19', '1'), pad('C17', '1'), pad('C12', '1')
T('+3V3', P, pin(45), (30.2, c13[1]))
T('+3V3', P, pin(44), (30.6, c13[1]))
T('+3V3', 0.3, c13, c19)
T('+1V1', P, pin(39), (32.6, c17[1]))
T('+3V3', S, pin(38), (33.0, 8.8), (33.71, 8.09), (33.71, 8.0))
V('+3V3', 33.71, 8.0)
T('+3V3', 0.3, (33.71, 8.0), c12)
gnd(pad('C13', '2'), 30.5, 6.3)
gnd(pad('C19', '2'), 29.54, 6.3)
gnd(pad('C17', '2'), 33.05, 6.3, (32.75, 6.6))
T('GND', P, pad('C12', '2'), (33.05, 6.3))

# ================= right column (pins 16..30, x 36.45) =================
XR = 35.375
V('+3V3', XR, 10.15)
T('+3V3', S, pin(30), (35.8, 9.9), (35.55, 10.15), (XR, 10.15))
T('/RUN', S, pin(26), (35.95, 11.5), (35.5, 11.05), (XR, 10.91))
V('/RUN', XR, 10.91)
Y1V1 = 13.19
for net, n, y in (('/SWDIO', 25, 11.67), ('/SWCLK', 24, 12.43), ('+1V1', 23, Y1V1), ('+3V3', 20, 13.95)):
    T(net, S, pin(n), (35.9, pin(n)[1]), (XR, y))
    V(net, XR, y)
# GP16..GP18 to the header
T('/GP18', S, pin(29), (37.85, 10.3), (38.15, 10.0), (38.15, 3.96), j6(10))
T('/GP17', S, pin(28), (38.15, 10.7), (38.45, 10.4), (38.45, 1.72), j6(11))
T('/GP16', S, pin(27), (38.45, 11.1), (38.75, 10.8), (38.75, 3.06), j6(12))
# decoupling
T('+3V3', P, pin(30), (pad('C14', '1')[0], 9.9))
gnd(pad('C14', '2'), 37.6, 7.75)
T('+1V1', P, pin(23), (pad('C16', '1')[0], 12.7))
gnd(pad('C16', '2'), 38.54, 11.7)
T('+3V3', P, pin(20), (pad('C11', '1')[0], 13.9))
# crystal
XI, XO, XM = 'Net-(U1-XIN)', 'Net-(U1-XOUT)', 'Net-(C21-Pad2)'
r16a, r16b = pad('R16', '1'), pad('R16', '2')
T(XO, S, pin(22), (39.0, 13.1), (39.3, 12.8), (39.3, 10.6), (39.5, 10.4), r16b)
T(XI, S, pin(21), (39.15, 13.5), (39.75, 12.9), (41.1, 12.9), (41.6, 13.4), pad('Y1', '1'))
T(XI, P, pad('Y1', '1'), pad('C20', '2'))
T(XM, P, r16a, (r16a[0], 11.3))
T(XM, P, r16a, pad('C21', '2'))
c21g = pad('C21', '1')
T('GND', P, c21g, (c21g[0], 11.3))
gnd(c21g, 42.48, 9.35)
gnd(pad('C11', '2'), 39.4, 14.05)
T('GND', P, (39.4, 14.05), (39.9, 14.05))
gnd(pad('C20', '1'), 42.05, 17.4)
# microSD: stubs to a via array, continued on the bottom layer by the router
T('/SD_DAT3', S, pin(19), (36.95, 14.3), (37.5, 14.85), (39.15, 14.85), (39.3, 15.0))
V('/SD_DAT3', 39.3, 15.0)
T('/SD_DAT2', S, pin(18), (36.9, 14.7), (37.4, 15.2), (38.1, 15.2), (38.6, 15.7))
V('/SD_DAT2', 38.6, 15.7)
T('/SD_DAT1', S, pin(17), (36.87, 15.1), (37.9, 16.13), (37.9, 16.4))
V('/SD_DAT1', 37.9, 16.4)
T('/SD_DAT0', S, pin(16), (36.84, 15.5), (37.2, 15.86), (37.2, 17.05))
V('/SD_DAT0', 37.2, 17.05)
T('/SD_CMD', S, pin(15), (35.8, 17.0), (36.4, 17.6), (38.0, 17.6))
V('/SD_CMD', 38.0, 17.6)
T('/SD_CLK', S, pin(14), (35.4, 17.3), (36.0, 17.9), (36.95, 17.9), (37.2, 18.15))
V('/SD_CLK', 37.2, 18.15)

# ================= bottom row (pins 1..15, y 16.15) =================
j7 = lambda n: pad('J7', str(n))
YB = 15.075
T('+1V1', S, pin(6), (32.2, YB))
V('+1V1', 32.2, YB)
T('/PSRAM_CS', S, pin(12), (34.6, YB))
V('/PSRAM_CS', 34.6, YB)
T('+3V3', S, pin(11), (34.2, 15.5), (33.84, 15.14), (33.84, YB))
V('+3V3', 33.84, YB)
# GP0..GP3 jog left, GP4..GP7 jog right, so the decoupling capacitors fit between the lanes
L = [30.35, 30.75, 31.15, 31.55]
R = [32.67, 33.07, 33.47, 33.87]
GP = ['/GP0', '/GP1', '/GP2', '/GP3', '/GP4_SDA', '/GP5_SCL', '/GP6', '/GP7']
jog = []                               # path from each pin to the top of its lane
for i, x in enumerate(L + R):
    p = pin(2 + i if i < 4 else 3 + i)
    y = 16.65 + 0.05 * (i if i < 4 else 7 - i)
    jog.append((p, (p[0], y), (x, y + abs(p[0] - x))))
T('/GP0', S, *jog[0], (L[0], 21.76), (29.66, 22.45), (24.44, 22.45), j7(5))
T('/GP1', S, *jog[1], (L[1], 21.79), (29.79, 22.75), (26.68, 22.75), j7(6))
T('/GP2', S, *jog[2], (L[2], 21.82), (29.27, 23.7), (28.4, 23.7), j7(7))
T('/GP3', S, *jog[3], (L[3], 22.96), j7(8))
r22, r23 = pad('R22', '2'), pad('R23', '2')
T('/GP4_SDA', S, *jog[4], (R[0], 23.5), j7(9))
T('/GP4_SDA', S, (R[0], r22[1]), r22)
T('/GP5_SCL', S, *jog[5], (R[1], 22.3), (34.93, 24.13), j7(10))
T('/GP5_SCL', S, r23, (r23[0], 23.4), j7(10))
T('/GP6', S, *jog[6], (R[2], 19.4), (R[2] + 4.5, 23.9), j7(11))
T('/GP7', S, *jog[7], (R[3], 19.3), (R[3] + 2.3, 21.6), (37.5, 21.6), (40.03, 24.13), j7(12))
T('/RGB_DIN', S, pin(13), (35.0, 19.5), (35.55, 20.05), pad('D1', '3'))
# decoupling and pull-ups
c9 = pad('C9', '1')
V('+3V3', 29.72, 16.25)
T('+3V3', S, pin(1), (30.2, 16.25), (29.72, 16.25))
T('+3V3', P, (29.72, 16.25), c9)
T('+1V1', S, pin(6), (32.2, pad('C15', '1')[1]))
T('+3V3', S, pin(11), (34.2, pad('C10', '1')[1]))
gnd(pad('C9', '2'), 29.72, 19.0)
gnd(pad('C15', '2'), 32.12, 19.1)
gnd(pad('C10', '2'), 34.45, 18.95)
T('+3V3', P, pad('R22', '1'), (32.1, 21.7))
V('+3V3', 32.1, 21.7)
T('+3V3', P, pad('R23', '1'), (34.2, 21.7))
V('+3V3', 34.2, 21.7)
T('+3V3', 0.3, pad('D1', '4'), (38.75, 21.9), pad('C29', '1'))
V('+3V3', 38.75, 21.9)
r17 = pad('R17', '2')
T('Net-(R17-Pad2)', S, r17, (r17[0], 21.6))
V('Net-(R17-Pad2)', r17[0], 21.6)

# ================= left column (pins 46..60, x 29.55) =================
u2, u3 = (lambda n: pad('U2', str(n))), (lambda n: pad('U3', str(n)))
SD0, SD1, SD2, SD3, SCK, SS = ('/QSPI_SD0', '/QSPI_SD1', '/QSPI_SD2', '/QSPI_SD3', '/QSPI_SCLK', '/QSPI_SS')
# SD3, SCLK, SD0: diagonal to lanes above the flash, then round its far side
T(SD3, S, pin(55), (28.4, 13.5), (24.9, 17.0), (20.85, 17.0), (20.55, 17.3), (20.55, 20.34), (20.85, 20.64), u2(7))
T(SD3, S, (20.55, 19.36), u3(7))
T(SCK, S, pin(56), (28.45, 13.9), (25.05, 17.3), (21.2, 17.3), (20.9, 17.6), (20.9, 19.06), (21.2, 19.36), u2(6))
T(SD0, S, pin(57), (28.5, 14.3), (25.2, 17.6), (22.99, 17.6), u2(5), (21.55, 18.09))
# SD2, SD1, SS: straight south into the flash
T(SD2, S, pin(58), (28.82, 14.7), (28.52, 15.0), (28.52, 19.08), (28.24, 19.36), u2(3))
T(SD1, S, pin(59), (29.0, 15.1), (28.84, 15.26), (28.84, 20.36), (28.56, 20.64), u2(2))
T(SS, S, pin(60), (29.3, 15.5), (29.16, 15.64), (29.16, 21.65), (28.9, 21.91), u2(1))
T(SS, S, (29.16, pad('R17', '1')[1]), pad('R17', '1'))
# PSRAM: the same bus on the bottom layer
V(SD0, 21.55, 18.09)
T(SD0, S, (21.55, 18.09), (19.2, 18.09), (18.9, 18.39), (18.9, 21.61), (19.2, 21.91), (19.5, 21.91), layer=B)
V(SD0, 19.5, 21.91)
T(SD0, S, (19.5, 21.91), u3(5))
V(SCK, 21.55, 19.36)
T(SCK, S, (21.55, 19.36), (20.78, 19.36), (19.5, 20.64), layer=B)
V(SCK, 19.5, 20.64)
T(SCK, S, (19.5, 20.64), u3(6))
XL = 30.625
T(SD2, S, pin(58), (30.1, 14.7), (30.5, 14.3), (XL, 14.22))
V(SD2, XL, 14.22)
T(SD2, S, (XL, 14.22), (29.9, 14.22), (27.92, 16.2), (14.8, 16.2), (14.4, 16.6), (14.4, 20.64), layer=B)
V(SD2, 14.4, 20.64)
T(SD2, S, (14.4, 20.64), u3(3))
T(SD1, S, pin(59), (30.3, 15.1), (30.43, 14.97), (XL, 14.97))
V(SD1, XL, 14.97)
T(SD1, S, (XL, 14.97), (29.9, 14.97), (28.37, 16.5), (15.4, 16.5), (15.0, 16.9), (15.0, 19.36), layer=B)
V(SD1, 15.0, 19.36)
T(SD1, S, (15.0, 19.36), u3(2))
CS = '/PSRAM_CS'
T(CS, S, (34.6, YB), (34.6, 15.5), (33.3, 16.8), (16.0, 16.8), (15.6, 17.2), (15.6, 18.09), layer=B)
V(CS, 15.6, 18.09)
T(CS, S, (15.6, 18.09), u3(1), pad('R19', '2'))
# supplies
V('+3V3', XL, 12.9)
T('+3V3', S, pin(53), (30.1, 12.7), (30.3, 12.9), (XL, 12.9))
T('+3V3', S, pin(54), (30.1, 13.1), (30.3, 12.9))
gnd(pad('C18', '2'), 27.3, 13.85)
T('GND', 0.3, u2(4), (26.5, u2(4)[1]))
T('+3V3', 0.3, (pad('C22', '1')[0], 22.05), (u2(8)[0], 22.05))

# ================= under U1, bottom layer =================
T('+1V1', 0.25, (30.5, 11.5), (31.2, 12.2), (31.2, 14.4), (31.875, YB), (32.2, YB), layer=B)
T('+1V1', P, (30.5, 11.5), (30.9, 11.1), (31.525, 11.1), (32.3, YT), layer=B)
T('+1V1', P, (XR, Y1V1), (31.2, Y1V1), layer=B)
for x, y in ((32.2, 11.95), (33.0, 11.95), (33.8, 11.95), (32.4, 14.05), (33.6, 14.05), (25.2, 19.0), (25.2, 21.0)):
    V('GND', x, y)

h.commit()
